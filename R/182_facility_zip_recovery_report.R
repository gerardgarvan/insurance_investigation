p180_get <- function(df, field, source) {
  col1 <- names(df)[1]; col2 <- names(df)[2]
  rows <- df[df[[col1]] == field, ]
  if (nrow(rows) != 1L) stop(glue("KEY field '{field}' not found (1 match required) in {source}"))
  as.character(rows[[col2]][1])
}

