get_primary_row <- function(df, label, source_name) {
  rows <- df[df$Analysis == label, ]
  if (nrow(rows) != 1L)
    stop(glue("'{label}' not found (or multiple matches) in {source_name} Model_Results"))
  rows[1, ]
}

