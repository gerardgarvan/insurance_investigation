# Helper: stop with a useful message if env is unset and no default applies
resolve_env <- function(var, default_path = NULL, required = FALSE) {
  val <- Sys.getenv(var, unset = "")
  if (nzchar(val)) {
    if (!file.exists(val)) stop(glue("{var}='{val}' — file not found"))
    return(val)
  }
  if (!is.null(default_path) && nzchar(default_path) && file.exists(default_path)) {
    message(glue("  {var} not set; using default: {basename(default_path)}"))
    return(default_path)
  }
  if (required) {
    missing_vars <- c()
    for (v in c("P182_P179_AFTER_XLSX", "P182_P179_AFTER_RDS",
                "P182_P180_AFTER_XLSX", "P182_DIAG_XLSX", "P182_R122_RDS")) {
      if (!nzchar(Sys.getenv(v, unset = ""))) missing_vars <- c(missing_vars, v)
    }
    stop(glue(
      "Required env var {var} is not set and no default is available.\n",
      "Set these env vars before sourcing:\n",
      paste(paste0("  Sys.setenv(", missing_vars, " = '<path>')"), collapse = "\n")
    ))
  }
  message(glue("  WARNING: {var} not set and default not found; some sections will be skipped"))
  return(NA_character_)
}

