# Format OR/CI for display
fmt_or <- function(row) {
  or  <- round(as.numeric(row$OR), 2)
  lo  <- round(as.numeric(row$CI_low), 2)
  hi  <- round(as.numeric(row$CI_high), 2)
  glue("OR {or} ({lo}–{hi})")  # en-dash
}

